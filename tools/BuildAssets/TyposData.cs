    public static void Write(string outputDirectory, Action<string> log)
    {
        WriteFile(Path.Combine(outputDirectory, "typos-ru.txt"),
            "Русские опечатки KeySwitch. Формат: неверно=верно. Строки, начинающиеся с #, — комментарии.",
            Russian);
        WriteFile(Path.Combine(outputDirectory, "typos-en.txt"),
            "English typos for KeySwitch. Format: wrong=correct. Lines starting with # are comments.",
            English);

        log($"typos: ru {Russian.Length}, en {English.Length} пар.");
    }

    private static void WriteFile(string path, string header, IReadOnlyCollection<string> entries)
    {
        var builder = new StringBuilder();
        builder.Append("# ").AppendLine(header);
        builder.AppendLine("# Замены применяются только к одиночному слову; многословные правые части допустимы.");
        foreach (var entry in entries)
            builder.AppendLine(entry);

        BuildOptions.WriteText(path, builder.ToString());
    }
